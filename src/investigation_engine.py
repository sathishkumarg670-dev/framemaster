# M10.2 - CROSS-CAMERA CANDIDATE GENERATION
# ============================================================

def generate_cross_video_candidates(
    profiles_by_video: Dict[
        str,
        List[TrackProfile]
    ],
    topology: dict
) -> List[dict]:

    candidates = []

    video_ids = sorted(
        profiles_by_video.keys()
    )

    for source_video in video_ids:

        source_profiles = (
            profiles_by_video[
                source_video
            ]
        )

        for target_video in video_ids:

            if (
                source_video
                ==
                target_video
            ):
                continue

            target_profiles = (
                profiles_by_video[
                    target_video
                ]
            )

            for source_profile in source_profiles:

                # Only REID_READY profiles can be
                # used for appearance matching.
                if not is_investigation_ready(
                    source_profile
                ):
                    continue

                if source_profile.embedding is None:
                    continue

                for target_profile in target_profiles:

                    if not is_investigation_ready(
                        target_profile
                    ):
                        continue

                    if target_profile.embedding is None:
                        continue

                    appearance_similarity = (
                        cosine_similarity(
                            source_profile.embedding,
                            target_profile.embedding
                        )
                    )

                    attribute_analysis = (
                        compare_attributes(
                            source_profile,
                            target_profile
                        )
                    )

                    temporal_analysis = (
                        analyze_temporal_consistency(
                            source_profile,
                            target_profile
                        )
                    )

                    topology_analysis = (
                        analyze_camera_topology(
                            topology,
                            source_video,
                            target_video
                        )
                    )

                    evidence = (
                        build_evidence_association(
                            source_profile,
                            target_profile,
                            appearance_similarity,
                            attribute_analysis,
                            temporal_analysis,
                            topology_analysis
                        )
                    )

                    candidate = {

                        "source_video":
                            source_video,

                        "source_track_id":
                            source_profile.track_id,

                        "source_profile_state":
                            get_profile_state(
                                source_profile
                            ),

                        "target_video":
                            target_video,

                        "target_track_id":
                            target_profile.track_id,

                        "target_profile_state":
                            get_profile_state(
                                target_profile
                            ),

                        "appearance_similarity":
                            round(
                                appearance_similarity,
                                6
                            ),

                        "attribute_analysis":
                            attribute_analysis,

                        "temporal_analysis":
                            temporal_analysis,

                        "topology_analysis":
                            topology_analysis,

                        "evidence":
                            evidence,

                        "candidate_type":
                            "cross_video_investigation_candidate",

                        "identity_confirmed":
                            False
                    }

                    candidates.append(
                        candidate
                    )

    return rank_candidates(
        candidates
    )


