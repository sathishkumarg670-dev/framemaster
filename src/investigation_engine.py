# CAMERA TOPOLOGY
# ============================================================

def ensure_default_topology() -> None:
    """
    Create an empty topology configuration if one
    does not already exist.

    Empty topology means that no physical camera
    transition relationship is assumed.
    """

    ensure_investigation_directory()

    if TOPOLOGY_FILE.exists():
        return

    topology = {
        "description": (
            "Optional camera transition constraints. "
            "Add known transitions only when supported "
            "by the actual camera deployment."
        ),
        "transitions": []
    }

    with open(
        TOPOLOGY_FILE,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            topology,
            file,
            indent=2
        )


def load_camera_topology() -> dict:
    """Load camera topology configuration."""

    ensure_default_topology()

    try:

        with open(
            TOPOLOGY_FILE,
            "r",
            encoding="utf-8"
        ) as file:

            return json.load(file)

    except (
        json.JSONDecodeError,
        OSError
    ):

        return {
            "description":
                "No valid topology configuration.",
            "transitions": []
        }


def find_camera_transition(
    topology: dict,
    source_video: str,
    target_video: str
) -> Optional[dict]:

    transitions = topology.get(
        "transitions",
        []
    )

    for transition in transitions:

        if (
            transition.get("from")
            == source_video
            and
            transition.get("to")
            == target_video
        ):

            return transition

    return None


def analyze_camera_topology(
    topology: dict,
    source_video: str,
    target_video: str
) -> dict:

    transition = find_camera_transition(
        topology,
        source_video,
        target_video
    )

    if transition is None:

        return {
            "topology_known": False,
            "transition_defined": False,
            "allowed": None,
            "minimum_transition_sec": None,
            "maximum_transition_sec": None,
            "reason":
                "No camera transition constraint "
                "is configured."
        }

    return {
        "topology_known": True,
        "transition_defined": True,
        "allowed":
            transition.get(
                "allowed",
                True
            ),
        "minimum_transition_sec":
            transition.get(
                "minimum_transition_sec"
            ),
        "maximum_transition_sec":
            transition.get(
                "maximum_transition_sec"
            ),
        "reason":
            transition.get(
                "reason",
                "Configured camera transition."
            )
    }


