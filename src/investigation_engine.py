def load_profiles_for_video(
    profile_file: Path
) -> List[TrackProfile]:
    """Load canonical profiles from one camera."""

    with open(
        profile_file,
        "r",
        encoding="utf-8"
    ) as file:

        data = json.load(file)

    profiles = []

    for item in data:

        try:

            profile = TrackProfile(
                **item
            )

            # Ensure readiness fields are correct even
            # if an older profile file is encountered.
            if hasattr(
                profile,
                "update_readiness"
            ):
                profile.update_readiness()

            profiles.append(profile)

        except Exception as exc:

            print(
                f"WARNING: Failed to load profile "
                f"from {profile_file}: {exc}"
            )

    return profiles


def discover_profile_files() -> List[Path]:
    """
    Discover all canonical profiles dynamically.

    No camera IDs are hardcoded.
    """

    if not PROFILES_DIRECTORY.exists():
        return []

    return sorted(
        PROFILES_DIRECTORY.glob(
            "*/canonical_track_profiles.json"
        )
    )


def load_all_profiles() -> Dict[str, List[TrackProfile]]:
    """
    Load canonical profiles for every discovered camera.
    """

    profiles_by_video = {}

    for profile_file in discover_profile_files():

        video_id = profile_file.parent.name

        profiles = load_profiles_for_video(
            profile_file
        )

        profiles_by_video[
            video_id
        ] = profiles

    return profiles_by_video


# ============================================================
# PROFILE READINESS
# ============================================================

def is_investigation_ready(
    profile: TrackProfile
) -> bool:
    """
    Determine whether a profile contains enough
    information for appearance-based investigation.
    """

    # Prefer the explicit M11 field.
    if hasattr(
        profile,
        "investigation_ready"
    ):

        if profile.investigation_ready:
            return True

    # Defensive fallback for older profiles.
    has_crops = (
        profile.total_crops > 0
    )

    has_attributes = (
        profile.attributes is not None
    )

    has_embedding = (
        profile.embedding is not None
        and len(profile.embedding) > 0
    )

    return (
        has_crops
        and
        has_attributes
        and
        has_embedding
    )


def get_profile_state(
    profile: TrackProfile
) -> str:

    if is_investigation_ready(profile):
        return "REID_READY"

    return "TRACK_ONLY"


