def main() -> None:

    parser = argparse.ArgumentParser(
        description=(
            "VISIONFORGE AI "
            "Unified Investigation Engine"
        )
    )

    parser.add_argument(
        "--limit",
        type=int,
        default=10,
        help=(
            "Number of candidates "
            "to display"
        )
    )

    args = parser.parse_args()

    ensure_investigation_directory()

    topology = load_camera_topology()

    profiles_by_video = (
        load_all_profiles()
    )

    if not profiles_by_video:

        print(
            "No unified canonical profile files found."
        )

        print(
            "Expected directory:",
            PROFILES_DIRECTORY
        )

        return

    print_profile_summary(
        profiles_by_video
    )

    candidates = (
        generate_cross_video_candidates(
            profiles_by_video,
            topology
        )
    )

    candidates_file = (
        save_candidates(
            candidates
        )
    )

    report = (
        build_investigation_report(
            profiles_by_video,
            candidates,
            topology
        )
    )

    report_file = (
        save_investigation_report(
            report
        )
    )

    print_candidates(
        candidates,
        limit=args.limit
    )

    total_tracks = sum(
        len(profiles)
        for profiles
        in profiles_by_video.values()
    )

    total_ready = sum(
        1
        for profiles
        in profiles_by_video.values()
        for profile in profiles
        if is_investigation_ready(
            profile
        )
    )

    print("=" * 72)
    print(
        "VISIONFORGE AI - "
        "M10 UNIFIED COMPLETE"
    )
    print("=" * 72)

    print(
        "Profile source:",
        PROFILES_DIRECTORY
    )

    print(
        "Videos:",
        len(
            profiles_by_video
        )
    )

    print(
        "Total profiles:",
        total_tracks
    )

    print(
        "REID_READY profiles:",
        total_ready
    )

    print(
        "TRACK_ONLY profiles:",
        total_tracks - total_ready
    )

    print(
        "Candidate associations:",
        len(candidates)
    )

    print(
        "Topology constraints:",
        len(
            topology.get(
                "transitions",
                []
            )
        )
    )

    print(
        "Candidates saved:",
        candidates_file
    )

    print(
        "Investigation report saved:",
        report_file
    )

    print(
        "Identity confirmation:",
        False
    )

    print("=" * 72)


if __name__ == "__main__":
    main()