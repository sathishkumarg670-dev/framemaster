# M10.2 - RE-ID SIMILARITY
# ============================================================

def cosine_similarity(
    embedding_a: List[float],
    embedding_b: List[float]
) -> float:

    vector_a = np.asarray(
        embedding_a,
        dtype=np.float32
    )

    vector_b = np.asarray(
        embedding_b,
        dtype=np.float32
    )

    if (
        vector_a.size == 0
        or
        vector_b.size == 0
    ):

        return 0.0

    if vector_a.shape != vector_b.shape:

        return 0.0

    norm_a = np.linalg.norm(
        vector_a
    )

    norm_b = np.linalg.norm(
        vector_b
    )

    if (
        norm_a == 0
        or
        norm_b == 0
    ):

        return 0.0

    similarity = (
        np.dot(
            vector_a,
            vector_b
        )
        /
        (
            norm_a
            *
            norm_b
        )
    )

    return float(similarity)


# ============================================================
# M10.3 - ATTRIBUTE COMPATIBILITY
# ============================================================

def compare_attributes(
    source: TrackProfile,
    target: TrackProfile
) -> dict:
    """
    Compare visual attributes available in both profiles.

    Unknown/missing values are not treated as mismatches.
    """

    source_attrs = source.attributes
    target_attrs = target.attributes

    if (
        source_attrs is None
        or
        target_attrs is None
    ):

        return {
            "available": False,
            "upper_body_color": None,
            "lower_body_color": None,
            "matched_attributes": 0,
            "compared_attributes": 0,
            "attribute_score": None
        }

    compared = 0
    matched = 0

    upper_match = None
    lower_match = None

    source_upper = (
        source_attrs.upper_body_color
    )

    target_upper = (
        target_attrs.upper_body_color
    )

    if (
        source_upper
        and
        target_upper
        and
        source_upper != "unknown"
        and
        target_upper != "unknown"
    ):

        compared += 1

        upper_match = (
            source_upper
            ==
            target_upper
        )

        if upper_match:
            matched += 1

    source_lower = (
        source_attrs.lower_body_color
    )

    target_lower = (
        target_attrs.lower_body_color
    )

    if (
        source_lower
        and
        target_lower
        and
        source_lower != "unknown"
        and
        target_lower != "unknown"
    ):

        compared += 1

        lower_match = (
            source_lower
            ==
            target_lower
        )

        if lower_match:
            matched += 1

    if compared == 0:

        attribute_score = None

    else:

        attribute_score = round(
            matched / compared,
            6
        )

    return {
        "available": compared > 0,
        "upper_body_color": upper_match,
        "lower_body_color": lower_match,
        "matched_attributes": matched,
        "compared_attributes": compared,
        "attribute_score": attribute_score
    }


# ============================================================
# M10.4 - TEMPORAL ANALYSIS
# ============================================================

def analyze_temporal_consistency(
    source: TrackProfile,
    target: TrackProfile
) -> dict:
    """
    Analyze video-relative temporal ordering.

    This does NOT assume synchronized wall-clock time.
    """

    source_last_seen = (
        source.last_seen_sec
    )

    target_first_seen = (
        target.first_seen_sec
    )

    time_gap = (
        target_first_seen
        -
        source_last_seen
    )

    ordered_after = (
        time_gap >= 0
    )

    overlap = (
        source.first_seen_sec
        <=
        target.last_seen_sec
        and
        target.first_seen_sec
        <=
        source.last_seen_sec
    )

    return {
        "clock_basis":
            "video_relative_seconds",

        "source_first_seen_sec":
            round(
                source.first_seen_sec,
                6
            ),

        "source_last_seen_sec":
            round(
                source.last_seen_sec,
                6
            ),

        "target_first_seen_sec":
            round(
                target.first_seen_sec,
                6
            ),

        "target_last_seen_sec":
            round(
                target.last_seen_sec,
                6
            ),

        "time_gap_sec":
            round(
                time_gap,
                6
            ),

        "ordered_after":
            ordered_after,

        "temporal_overlap":
            overlap,

        "temporally_consistent":
            ordered_after,

        "interpretation":
            (
                "Target starts after source ends "
                "under video-relative timestamps."
                if ordered_after
                else
                "Target starts before source ends "
                "under video-relative timestamps. "
                "This does not establish physical "
                "impossibility when camera clocks "
                "are not synchronized."
            )
    }


# ============================================================
# M10.6 - EVIDENCE ASSOCIATION
# ============================================================

def build_evidence_association(
    source: TrackProfile,
    target: TrackProfile,
    appearance_similarity: float,
    attribute_analysis: dict,
    temporal_analysis: dict,
    topology_analysis: dict
) -> dict:

    supporting_signals = []

    if appearance_similarity > 0:

        supporting_signals.append(
            "appearance_embedding"
        )

    if (
        attribute_analysis.get(
            "upper_body_color"
        )
        is True
    ):

        supporting_signals.append(
            "upper_body_color"
        )

    if (
        attribute_analysis.get(
            "lower_body_color"
        )
        is True
    ):

        supporting_signals.append(
            "lower_body_color"
        )

    if (
        temporal_analysis.get(
            "temporally_consistent"
        )
        is True
    ):

        supporting_signals.append(
            "temporal_order"
        )

    if (
        topology_analysis.get(
            "allowed"
        )
        is True
    ):

        supporting_signals.append(
            "camera_transition"
        )

    conflicting_signals = []

    if (
        temporal_analysis.get(
            "temporally_consistent"
        )
        is False
    ):

        conflicting_signals.append(
            "temporal_order"
        )

    if (
        topology_analysis.get(
            "allowed"
        )
        is False
    ):

        conflicting_signals.append(
            "camera_transition"
        )

    return {

        "supporting_signals":
            supporting_signals,

        "conflicting_signals":
            conflicting_signals,

        "source_representative_crop":
            source.representative_crop,

        "target_representative_crop":
            target.representative_crop,

        "evidence_available":
            True,

        "identity_confirmed":
            False
    }


# ============================================================
# M10.7 - CANDIDATE RANKING
# ============================================================

def candidate_sort_key(
    candidate: dict
):

    appearance = candidate.get(
        "appearance_similarity",
        0.0
    )

    attribute_analysis = candidate.get(
        "attribute_analysis",
        {}
    )

    attribute_score = (
        attribute_analysis.get(
            "attribute_score"
        )
    )

    if attribute_score is None:
        attribute_score = -1.0

    temporal = candidate.get(
        "temporal_analysis",
        {}
    )

    temporal_match = (
        1
        if temporal.get(
            "temporally_consistent"
        )
        else 0
    )

    return (
        appearance,
        attribute_score,
        temporal_match
    )


def rank_candidates(
    candidates: List[dict]
) -> List[dict]:
    """
    Sort candidates by explicit evidence signals.

    No universal identity threshold is used.
    """

    ranked = sorted(
        candidates,
        key=candidate_sort_key,
        reverse=True
    )

    for index, candidate in enumerate(
        ranked,
        start=1
    ):

        candidate[
            "investigation_rank"
        ] = index

    return ranked


